#!/system/bin/sh
#
# Замер на самом устройстве: сколько ждать стола, когда образ уже развёрнут.
#
# Готовность определяется тем же способом, каким её видит приложение, —
# подключением к маячку на 5910. Через /proc/net/tcp смотреть нельзя: сокеты
# программ внутри образа там из-под adb не видны, хотя порт открыт и принимает
# подключения. Проверка, построенная на этом файле, показывала бы вечное
# ожидание при полностью рабочем столе.
#
# К порту 5901 не подключаемся вовсе: недочитанный баннер RFB TigerVNC считает
# обрывом и после нескольких таких заносит 127.0.0.1 в чёрный список — замер
# сломал бы то, что меряет.
#
# Секунды берём из /proc/uptime: там сотые доли и никакой зависимости от часов.

PKG=ru.codoceh.stol
PORT=5910
LIMIT_CS=$(( ${1:-600} * 100 ))

cs() { read a b < /proc/uptime; echo "${a%.*}${a#*.}"; }
beacon_open() { echo x | nc -w 1 127.0.0.1 "$PORT" >/dev/null 2>&1; }
# Скобки в шаблоне обязательны: без них grep находит собственную командную
# строку в списке процессов, и остатки «находятся» всегда.
leftovers() { ps -A -o ARGS 2>/dev/null | grep -c '[X]tigervnc'; }

# Остатки прошлого стола сделали бы замер поддельным: ждать было бы нечего,
# и «повторный запуск» показал бы прекрасные ноль секунд.
if [ "$(leftovers)" != "0" ]; then
    echo "ERR=перед замером в памяти остался Xtigervnc — стол с прошлого раза не погашен"
    exit 1
fi
if beacon_open; then
    echo "ERR=перед замером маячок уже отвечает — стол с прошлого раза не погашен"
    exit 1
fi

T0=$(cs)
am start -n "$PKG/.MainActivity" >/dev/null 2>&1 || { echo "ERR=приложение не запустилось"; exit 1; }

while :; do
    N=$(cs)
    E=$((N - T0))
    if beacon_open; then
        echo "BEACON_CS=$E"
        exit 0
    fi
    if [ "$E" -gt "$LIMIT_CS" ]; then
        echo "ERR=стол не поднялся за $((LIMIT_CS / 100)) с"
        exit 1
    fi
    sleep 0.2
done
